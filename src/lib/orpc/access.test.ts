  test("the built-in community roles keep exactly the access their levels had", () => {
    const rank = { member: 0, editor: 1, admin: 2 } as const;
    for (const [path, level] of Object.entries(LEVEL_BEFORE_PERMISSIONS)) {
      const permission = EXPECTED[path].replace(/^community:/, "");
      for (const role of ["member", "editor", "admin", "owner"] as const) {
        const before = role === "owner" || rank[role] >= rank[level];
        expect([path, role, grantsHold(COMMUNITY_ROLE_GRANTS[role], permission)]).toStrictEqual([path, role, before]);
      }
    }
  });

  test("site staff hold every permission a procedure asks for, but none of the people-and-keys ones", () => {
    const staff = PLATFORM_ROLE_GRANTS.staff;
    const peopleAndKeys = /^platform:(user|session|apiKey|audit|owy|delegation):/;
    for (const [path, access] of Object.entries(EXPECTED)) {
      if (access === "public" || access === "authed") continue;
      const permission = access.replace(/^(platform|community):/, "");
      expect([path, grantsHold(staff, permission)]).toStrictEqual([path, !peopleAndKeys.test(access)]);
    }
  });

  test("the door role only checks people in", () => {
    const door = Object.entries(EXPECTED)
      .filter(([, access]) => access.startsWith("community:"))
      .filter(([, access]) => grantsHold(COMMUNITY_ROLE_GRANTS.door, access.slice("community:".length)))
      .map(([path]) => path)
      .toSorted();
    expect(door).toStrictEqual([
      "attendees.checkins",
      "attendees.recent",
      "attendees.scan",
      "events.list",
      "openSpaces.listByCommunity",
      "shell.status",
    ]);
  });
